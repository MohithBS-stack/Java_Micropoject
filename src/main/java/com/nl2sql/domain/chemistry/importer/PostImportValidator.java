package com.nl2sql.domain.chemistry.importer;

import com.nl2sql.database.DatabaseManager;
import com.nl2sql.domain.chemistry.validation.ValidationIssue;
import com.nl2sql.domain.chemistry.validation.ValidationReport;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/**
 * Performs post‑import validation on the populated chemistry SQLite database.
 * It checks foreign‑key integrity, row‑count consistency with the source Excel report,
 * and primary‑key uniqueness. Validation results are returned as a {@link ValidationReport}
 * which follows the same structure used by the dataset validator.
 */
public class PostImportValidator {
    private final DatabaseManager dbManager;

    public PostImportValidator(DatabaseManager dbManager) {
        this.dbManager = dbManager;
    }

    /**
     * Validates the imported database against the source import report.
     *
     * @param importReport the report generated by {@link ChemistryExcelImporter}
     * @return a {@link ValidationReport} summarising any issues found.
     */
    public ValidationReport validate(ChemistryImportReport importReport) {
        List<ValidationIssue> issues = new ArrayList<>();
        Map<String, List<String>> sheetColumnsMap = new java.util.LinkedHashMap<>();
        Map<String, Integer> sheetRowCountsMap = new java.util.LinkedHashMap<>();
        // Acquire connection using try-with-resources
        try (Connection conn = dbManager.getConnection()) {
            // 1. Foreign‑key integrity (PRAGMA foreign_key_check returns rows for violations)
            try (PreparedStatement pragmaFk = conn.prepareStatement("PRAGMA foreign_key_check")) {
                try (ResultSet rs = pragmaFk.executeQuery()) {
                    while (rs.next()) {
                        String table = rs.getString("table");
                        String rowId = rs.getString("rowid");
                        String parent = rs.getString("parent");
                        String fkid = rs.getString("fkid");
                        String msg = String.format("Foreign key violation in table '%s' rowid %s referencing parent table '%s' (fkid=%s)",
                                table, rowId, parent, fkid);
                        Integer rowIdInt = (rowId != null && !rowId.isEmpty()) ? Integer.valueOf(rowId) : null;
                        issues.add(new ValidationIssue(ValidationIssue.Severity.ERROR, table, rowIdInt, null, msg));
                    }
                }
            }

            // 2. Row‑count consistency with source report
            for (ChemistryImportReport.SheetReport sr : importReport.getSheetReports()) {
                String table = sr.tableName;
                try (PreparedStatement cntStmt = conn.prepareStatement("SELECT COUNT(*) AS cnt FROM " + table)) {
                    try (ResultSet rs = cntStmt.executeQuery()) {
                        if (rs.next()) {
                            int actual = rs.getInt("cnt");
                            if (actual != sr.importedRowCount) {
                                String msg = String.format("Row count mismatch for table '%s': imported %d rows, but DB contains %d rows", 
                                        table, sr.importedRowCount, actual);
                                issues.add(new ValidationIssue(ValidationIssue.Severity.WARNING, table, null, null, msg));
                            }
                        }
                    }
                } catch (SQLException e) {
                    String msg = String.format("Unable to query row count for table '%s': %s", table, e.getMessage());
                    issues.add(new ValidationIssue(ValidationIssue.Severity.ERROR, table, null, null, msg));
                }
            }

            // 3. Primary‑key uniqueness (for each table, ensure PK columns are unique)
            List<String> tables = new ArrayList<>();
            try (PreparedStatement tblStmt = conn.prepareStatement("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'")) {
                try (ResultSet rs = tblStmt.executeQuery()) {
                    while (rs.next()) {
                        tables.add(rs.getString("name"));
                    }
                }
            }
            for (String tbl : tables) {
                List<String> pkCols = new ArrayList<>();
                try (PreparedStatement infoStmt = conn.prepareStatement("PRAGMA table_info(" + tbl + ")")) {
                    try (ResultSet rs = infoStmt.executeQuery()) {
                        while (rs.next()) {
                            int pk = rs.getInt("pk");
                            if (pk > 0) {
                                pkCols.add(rs.getString("name"));
                            }
                        }
                    }
                }
                if (!pkCols.isEmpty()) {
                    String colsCsv = String.join(", ", pkCols);
                    String dupSql = String.format("SELECT %s, COUNT(*) AS cnt FROM %s GROUP BY %s HAVING cnt > 1", colsCsv, tbl, colsCsv);
                    try (PreparedStatement dupStmt = conn.prepareStatement(dupSql)) {
                        try (ResultSet rs = dupStmt.executeQuery()) {
                            while (rs.next()) {
                                StringBuilder keyVals = new StringBuilder();
                                for (String pkc : pkCols) {
                                    keyVals.append(pkc).append("=").append(rs.getString(pkc)).append(", ");
                                }
                                String msg = String.format("Duplicate primary‑key values detected in table '%s': %s",
                                        tbl, keyVals.toString());
                                issues.add(new ValidationIssue(ValidationIssue.Severity.ERROR, tbl, null, null, msg));
                            }
                        }
                    }
                }
            }

            for (String tbl : tables) {
                List<String> cols = new ArrayList<>();
                try (PreparedStatement infoStmt = conn.prepareStatement("PRAGMA table_info(" + tbl + ")")) {
                    try (ResultSet rs = infoStmt.executeQuery()) {
                        while (rs.next()) {
                            cols.add(rs.getString("name"));
                        }
                    }
                }
                sheetColumnsMap.put(tbl, cols);
            }
        } catch (SQLException e) {
            issues.add(new ValidationIssue(ValidationIssue.Severity.ERROR, null, null, null, "SQL error during post‑import validation: " + e.getMessage()));
        }

        for (ChemistryImportReport.SheetReport sr : importReport.getSheetReports()) {
            sheetRowCountsMap.put(sr.sheetName, sr.importedRowCount);
        }

        ValidationReport.Status status = ValidationReport.Status.PASS;
        for (ValidationIssue vi : issues) {
            if (vi.getSeverity() == ValidationIssue.Severity.ERROR) {
                status = ValidationReport.Status.ERROR;
                break;
            } else if (vi.getSeverity() == ValidationIssue.Severity.WARNING && status != ValidationReport.Status.ERROR) {
                status = ValidationReport.Status.WARNING;
            }
        }
        return new ValidationReport("post-import", sheetColumnsMap, sheetRowCountsMap, issues, status);
    }
}
